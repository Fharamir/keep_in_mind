import 'dart:async';
import 'package:file_picker/file_picker.dart';
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import '../../l10n/app_localizations.dart';
import '../../services/storage_service.dart';
import '../../utils/tag_helper.dart';

class AddMemorySheet extends StatefulWidget {
  final StorageService storage;
  final String? initialText;
  final String? initialSubject;

  const AddMemorySheet({
    super.key,
    required this.storage,
    this.initialText,
    this.initialSubject,
  });

  @override
  State<AddMemorySheet> createState() => _AddMemorySheetState();
}

class _AddMemorySheetState extends State<AddMemorySheet> {
  static const MethodChannel _mediaChannel =
      MethodChannel('com.example.keep_in_mind/media');

  late final TextEditingController _contentController;
  late final TextEditingController _titleController;
  final TextEditingController _newTagController = TextEditingController();
  
  final Set<String> _selectedTags = {};

  PlatformFile? _selectedFile;
  String? _selectedMimeType;
  String? _autoGeneratedTitle;
  String? _autoAssignedTag;
  bool _isPinned = false;
  bool _isSaving = false;
  bool _isRecording = false;
  int _recordingSeconds = 0;
  Timer? _recordingTimer;

  AppLocalizations get strings => widget.storage.l10n;

  @override
  void initState() {
    super.initState();
    _contentController = TextEditingController(text: widget.initialText ?? '');
    _titleController = TextEditingController(text: widget.initialSubject ?? '');
  }

  @override
  void dispose() {
    _recordingTimer?.cancel();
    if (_isRecording) {
      _mediaChannel.invokeMethod('stopAudioRecording').ignore();
    }
    _contentController.dispose();
    _titleController.dispose();
    _newTagController.dispose();
    super.dispose();
  }

  Future<void> _pasteFromClipboard() async {
    final data = await Clipboard.getData(Clipboard.kTextPlain);
    final text = data?.text?.trim();
    if (text != null && text.isNotEmpty) {
      setState(() {
        _contentController.text = text;
      });
    }
  }

  void _applyAttachment({
    required PlatformFile file,
    required String mimeType,
    required String defaultTitle,
    required String defaultTag,
  }) {
    setState(() {
      if (_autoAssignedTag != null) {
        _selectedTags.remove(_autoAssignedTag);
      }
      final currentTitle = _titleController.text.trim();
      final isDefaultOrEmpty =
          currentTitle.isEmpty || currentTitle == _autoGeneratedTitle;

      _selectedFile = file;
      _selectedMimeType = mimeType;
      _autoAssignedTag = defaultTag;
      _selectedTags.add(defaultTag);

      if (isDefaultOrEmpty) {
        _titleController.text = defaultTitle;
        _autoGeneratedTitle = defaultTitle;
      }
    });
  }

  void _clearAttachment() {
    setState(() {
      if (_autoAssignedTag != null) {
        _selectedTags.remove(_autoAssignedTag);
        _autoAssignedTag = null;
      }
      final currentTitle = _titleController.text.trim();
      if (_autoGeneratedTitle != null && currentTitle == _autoGeneratedTitle) {
        _titleController.clear();
      }
      _autoGeneratedTitle = null;
      _selectedFile = null;
      _selectedMimeType = null;
    });
  }

  Future<void> _capturePhotoFromCamera() async {
    try {
      final res =
          await _mediaChannel.invokeMapMethod<String, dynamic>('capturePhoto');
      if (res != null && mounted) {
        final path = res['filePath'] as String?;
        final name = res['fileName'] as String? ?? 'foto.jpg';
        final size = (res['fileSizeBytes'] as num?)?.toInt() ?? 0;
        final mime = res['mimeType'] as String? ?? 'image/jpeg';

        if (path != null && path.isNotEmpty) {
          _applyAttachment(
            file: PlatformFile(name: name, path: path, size: size),
            mimeType: mime,
            defaultTitle: strings.defaultPhotoTitle,
            defaultTag: 'immagine',
          );
        }
      }
    } on PlatformException catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            behavior: SnackBarBehavior.floating,
            content: Text(e.message ?? strings.cameraError),
          ),
        );
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('${strings.cameraError}: $e')),
        );
      }
    }
  }

  Future<void> _toggleAudioRecording() async {
    if (_isRecording) {
      _recordingTimer?.cancel();
      final durationSec = _recordingSeconds;
      setState(() {
        _isRecording = false;
      });
      try {
        final res = await _mediaChannel
            .invokeMapMethod<String, dynamic>('stopAudioRecording');
        if (res != null && mounted) {
          final path = res['filePath'] as String?;
          final name = res['fileName'] as String? ?? 'registrazione.m4a';
          final size = (res['fileSizeBytes'] as num?)?.toInt() ?? 0;
          final mime = res['mimeType'] as String? ?? 'audio/mp4';

          if (path != null && path.isNotEmpty) {
            _applyAttachment(
              file: PlatformFile(name: name, path: path, size: size),
              mimeType: mime,
              defaultTitle: strings.defaultVoiceNoteTitle(durationSec),
              defaultTag: 'audio',
            );
          }
        }
      } catch (e) {
        if (mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(content: Text('${strings.audioSaveError}: $e')),
          );
        }
      }
    } else {
      try {
        final started =
            await _mediaChannel.invokeMethod<bool>('startAudioRecording');
        if (started == true && mounted) {
          setState(() {
            _isRecording = true;
            _recordingSeconds = 0;
          });
          final maxAudioSeconds = widget.storage.maxAudioDurationSeconds;
          _recordingTimer = Timer.periodic(const Duration(seconds: 1), (_) {
            if (!mounted) return;
            if (maxAudioSeconds > 0 &&
                _recordingSeconds + 1 >= maxAudioSeconds) {
              final limitLabel =
                  StorageService.formatAudioDurationOption(maxAudioSeconds, strings);
              ScaffoldMessenger.of(context).showSnackBar(
                SnackBar(
                  behavior: SnackBarBehavior.floating,
                  content: Text(strings.audioMaxDurationSaved(limitLabel)),
                ),
              );
              _toggleAudioRecording();
              return;
            }
            setState(() {
              _recordingSeconds++;
            });
          });
        }
      } on PlatformException catch (e) {
        if (mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(
              behavior: SnackBarBehavior.floating,
              content: Text(e.message ?? strings.micPermissionDenied),
            ),
          );
        }
      } catch (e) {
        if (mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(content: Text('${strings.micPermissionDenied}: $e')),
          );
        }
      }
    }
  }

  Future<void> _pickFile({required bool imageOnly}) async {
    try {
      final result = await FilePicker.platform.pickFiles(
        type: imageOnly ? FileType.image : FileType.any,
        withData: true,
      );
      if (result != null && result.files.isNotEmpty) {
        final file = result.files.first;
        final maxBytes = widget.storage.maxFileSizeBytes;
        if (maxBytes != null && file.size > maxBytes) {
          if (mounted) {
            ScaffoldMessenger.of(context).showSnackBar(
              SnackBar(
                behavior: SnackBarBehavior.floating,
                content: Text(
                  strings.fileTooBigError(
                    StorageService.formatFileSizeOption(
                      widget.storage.maxFileSizeMb,
                      strings,
                    ),
                  ),
                ),
              ),
            );
          }
          return;
        }
        final ext = (file.extension ?? '').toLowerCase();
        String mime = 'application/octet-stream';
        String defaultTag = 'file';
        if (imageOnly ||
            ['jpg', 'jpeg', 'png', 'gif', 'webp'].contains(ext)) {
          mime = ext == 'png' ? 'image/png' : 'image/jpeg';
          defaultTag = 'immagine';
        } else if (['mp3', 'wav', 'm4a', 'aac', 'ogg'].contains(ext)) {
          mime = 'audio/mp4';
          defaultTag = 'audio';
        } else if (ext == 'pdf') {
          mime = 'application/pdf';
        } else if (['txt', 'md', 'json', 'csv'].contains(ext)) {
          mime = 'text/plain';
        }

        _applyAttachment(
          file: file,
          mimeType: mime,
          defaultTitle: file.name,
          defaultTag: defaultTag,
        );
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('${strings.filePickError}: $e')),
        );
      }
    }
  }

  Future<void> _save() async {
    final strings = widget.storage.l10n;
    final rawText = _contentController.text.trim();
    final rawSubject = _titleController.text.trim();
    if (rawText.isEmpty && _selectedFile == null) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text(strings.errorNoEmptyItem),
        ),
      );
      return;
    }

    setState(() => _isSaving = true);

    final tags = _selectedTags.toList();

    final saved = await widget.storage.addSharedOrManualItem(
      rawText: rawText,
      rawSubject: rawSubject.isNotEmpty ? rawSubject : null,
      filePath: _selectedFile?.path,
      fileName: _selectedFile?.name,
      mimeType: _selectedMimeType,
      fileSizeBytes: _selectedFile?.size,
      fileBytes: _selectedFile?.bytes,
      customTags: tags,
      isPinned: _isPinned,
      source: strings.badgeLocal,
    );

    if (mounted) {
      Navigator.of(context).pop(saved);
    }
  }

  @override
  Widget build(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    final strings = widget.storage.l10n;
    final bottomInset = MediaQuery.of(context).viewInsets.bottom;

    return Padding(
      padding: EdgeInsets.only(
        left: 20,
        right: 20,
        top: 16,
        bottom: bottomInset + 20,
      ),
      child: SingleChildScrollView(
        child: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Center(
              child: Container(
                width: 40,
                height: 4,
                decoration: BoxDecoration(
                  color: scheme.outlineVariant,
                  borderRadius: BorderRadius.circular(4),
                ),
              ),
            ),
            const SizedBox(height: 16),
            Row(
              children: [
                Icon(Icons.add_task_rounded, color: scheme.primary),
                const SizedBox(width: 8),
                Text(
                  strings.addSheetTitle,
                  style: Theme.of(context).textTheme.titleMedium?.copyWith(
                        fontWeight: FontWeight.w700,
                      ),
                ),
                const Spacer(),
                Tooltip(
                  message: strings.tooltipPasteClipboard,
                  child: TextButton.icon(
                    onPressed: _pasteFromClipboard,
                    icon: const Icon(Icons.content_paste_rounded, size: 16),
                    label: Text(strings.actionPaste),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 12),
            TextField(
              controller: _contentController,
              maxLines: 4,
              minLines: 2,
              decoration: InputDecoration(
                labelText: strings.inputContentLabel,
                hintText: strings.inputContentHint,
                border: OutlineInputBorder(
                  borderRadius: BorderRadius.circular(14),
                ),
              ),
            ),
            const SizedBox(height: 12),
            _buildMetadataFields(scheme),
          ],
        ),
      ),
    );
  }

  Widget _buildMetadataFields(ColorScheme scheme) {
    final availableTags = widget.storage.availableTags;

    void addNewTag() {
      // Keep only alphanumeric characters, hyphens, and underscores
      final raw = _newTagController.text.trim().toLowerCase();
      final sanitized = raw
          .replaceAll(RegExp(r'[^a-z0-9\-_]'), '')
          .replaceAll(RegExp(r'[\s]+'), '');

      if (sanitized.isEmpty) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            behavior: SnackBarBehavior.floating,
            content: Text(strings.tagInvalidCharsError),
          ),
        );
        return;
      }

      if (sanitized.length > 20) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            behavior: SnackBarBehavior.floating,
            content: Text(strings.tagMaxLengthError),
          ),
        );
        return;
      }

      setState(() {
        _selectedTags.add(sanitized);
        _newTagController.clear();
      });
    }

    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      mainAxisSize: MainAxisSize.min,
      children: [
        Row(
          children: [
            Expanded(
              child: TextField(
                controller: _titleController,
                decoration: InputDecoration(
                  labelText: strings.inputTitleLabel,
                  hintText: strings.inputTitleHint,
                  prefixIcon: const Icon(Icons.title_rounded, size: 18),
                  border: OutlineInputBorder(
                    borderRadius: BorderRadius.circular(14),
                  ),
                ),
              ),
            ),
            const SizedBox(width: 8),
            PopupMenuButton<String>(
              tooltip: strings.btnAttachFile,
              onSelected: (value) {
                if (value == 'camera') {
                  _capturePhotoFromCamera();
                } else if (value == 'gallery') {
                  _pickFile(imageOnly: true);
                } else if (value == 'file') {
                  _pickFile(imageOnly: false);
                }
              },
              itemBuilder: (context) => [
                PopupMenuItem(
                  value: 'camera',
                  child: ListTile(
                    leading: const Icon(Icons.camera_alt_outlined),
                    title: Text(strings.btnPhoto),
                    dense: true,
                    contentPadding: EdgeInsets.zero,
                  ),
                ),
                PopupMenuItem(
                  value: 'gallery',
                  child: ListTile(
                    leading: const Icon(Icons.image_outlined),
                    title: Text(strings.typeImage),
                    dense: true,
                    contentPadding: EdgeInsets.zero,
                  ),
                ),
                PopupMenuItem(
                  value: 'file',
                  child: ListTile(
                    leading: const Icon(Icons.attach_file_rounded),
                    title: Text(strings.btnAttachFile),
                    dense: true,
                    contentPadding: EdgeInsets.zero,
                  ),
                ),
              ],
              child: Container(
                width: 48,
                height: 48,
                decoration: BoxDecoration(
                  color: scheme.primaryContainer.withValues(alpha: 0.5),
                  borderRadius: BorderRadius.circular(12),
                ),
                child: Icon(
                  Icons.image_outlined,
                  color: scheme.primary,
                ),
              ),
            ),
            const SizedBox(width: 6),
            SizedBox(
              width: 48,
              height: 48,
              child: IconButton(
                onPressed: _toggleAudioRecording,
                icon: Icon(
                  _isRecording ? Icons.stop_rounded : Icons.mic_rounded,
                  color: _isRecording ? Colors.red : scheme.primary,
                ),
                tooltip: _isRecording ? strings.btnStopAudio : strings.btnRecordAudio,
                style: IconButton.styleFrom(
                  backgroundColor: _isRecording
                      ? Colors.red.withValues(alpha: 0.18)
                      : scheme.primaryContainer.withValues(alpha: 0.5),
                  shape: RoundedRectangleBorder(
                    borderRadius: BorderRadius.circular(12),
                  ),
                ),
              ),
            ),
          ],
        ),
        if (_isRecording) ...[
          const SizedBox(height: 8),
          Container(
            padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 8),
            decoration: BoxDecoration(
              color: Colors.red.withValues(alpha: 0.1),
              borderRadius: BorderRadius.circular(10),
            ),
            child: Row(
              children: [
                const Icon(
                  Icons.fiber_manual_record,
                  color: Colors.red,
                  size: 16,
                ),
                const SizedBox(width: 8),
                Expanded(
                  child: Builder(
                    builder: (context) {
                      final maxAudioSeconds =
                          widget.storage.maxAudioDurationSeconds;
                      final durationStr = maxAudioSeconds > 0
                          ? '${_recordingSeconds}s / ${maxAudioSeconds}s'
                          : '${_recordingSeconds}s / ∞ (${strings.optionNoLimit})';
                      return Text(
                        '${strings.audioRecordingLabel}... $durationStr',
                        style: const TextStyle(
                          color: Colors.red,
                          fontWeight: FontWeight.w700,
                          fontSize: 12,
                        ),
                      );
                    },
                  ),
                ),
              ],
            ),
          ),
        ],
        if (_selectedFile != null) ...[
          const SizedBox(height: 10),
          Container(
            padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 8),
            decoration: BoxDecoration(
              color: scheme.primaryContainer.withValues(alpha: 0.4),
              borderRadius: BorderRadius.circular(12),
            ),
            child: Row(
              children: [
                Icon(
                  (_selectedMimeType ?? '').startsWith('image/')
                      ? Icons.image_rounded
                      : (_selectedMimeType ?? '').startsWith('audio/')
                          ? Icons.mic_rounded
                          : Icons.insert_drive_file_rounded,
                  size: 18,
                  color: scheme.primary,
                ),
                const SizedBox(width: 8),
                Expanded(
                  child: Text(
                    _selectedFile!.name,
                    maxLines: 1,
                    overflow: TextOverflow.ellipsis,
                    style: const TextStyle(
                      fontSize: 13,
                      fontWeight: FontWeight.w600,
                    ),
                  ),
                ),
                IconButton(
                  onPressed: _clearAttachment,
                  icon: const Icon(Icons.close_rounded, size: 18),
                  tooltip: strings.tooltipRemoveAttachment,
                  visualDensity: VisualDensity.compact,
                ),
              ],
            ),
          ),
        ],
        const SizedBox(height: 14),
        Row(
          children: [
            Icon(Icons.tag_rounded, size: 18, color: scheme.primary),
            const SizedBox(width: 8),
            Text(
              '${strings.detailSectionTags}:',
              style: TextStyle(
                fontSize: 13,
                fontWeight: FontWeight.w700,
                color: scheme.onSurfaceVariant,
              ),
            ),
            const Spacer(),
            FilterChip(
              selected: _isPinned,
              onSelected: (v) => setState(() => _isPinned = v),
              avatar: Icon(
                _isPinned
                    ? Icons.push_pin_rounded
                    : Icons.push_pin_outlined,
                size: 16,
              ),
              label: Text(strings.filterPinned),
            ),
          ],
        ),
        const SizedBox(height: 8),
        Wrap(
          spacing: 8,
          runSpacing: 6,
          children: [
            ...{...availableTags, ..._selectedTags}.map((tag) {
              final isSelected = _selectedTags.contains(tag);
              final color = TagVisuals.colorForTag(tag);
              return FilterChip(
                selected: isSelected,
                avatar: Icon(
                  TagVisuals.iconForTag(tag),
                  size: 16,
                  color: color,
                ),
                label: Text(
                  strings.tagLabel(tag),
                  style: TextStyle(
                    fontWeight:
                        isSelected ? FontWeight.w700 : FontWeight.w600,
                    color: isSelected ? color : null,
                  ),
                ),
                selectedColor: color.withValues(alpha: 0.18),
                checkmarkColor: color,
                side: BorderSide(
                  color: isSelected
                      ? color
                      : scheme.outlineVariant.withValues(alpha: 0.7),
                ),
                onSelected: (selected) {
                  setState(() {
                    if (selected) {
                      _selectedTags.add(tag);
                    } else {
                      _selectedTags.remove(tag);
                    }
                  });
                },
              );
            }),
          ],
        ),
        const SizedBox(height: 8),
        Row(
          children: [
            Expanded(
              child: SizedBox(
                height: 42,
                child: TextField(
                  controller: _newTagController,
                  maxLength: 20,
                  onSubmitted: (_) => addNewTag(),
                  decoration: InputDecoration(
                    hintText: strings.createNewTagHint,
                    counterText: '',
                    contentPadding: const EdgeInsets.symmetric(horizontal: 12),
                    border: OutlineInputBorder(
                      borderRadius: BorderRadius.circular(10),
                    ),
                  ),
                ),
              ),
            ),
            const SizedBox(width: 8),
            SizedBox(
              height: 42,
              child: OutlinedButton.icon(
                onPressed: addNewTag,
                icon: const Icon(Icons.add_rounded, size: 16),
                label: Text(strings.btnAddTag),
                style: OutlinedButton.styleFrom(
                  shape: RoundedRectangleBorder(
                    borderRadius: BorderRadius.circular(10),
                  ),
                ),
              ),
            ),
          ],
        ),
        const SizedBox(height: 18),
        SizedBox(
          width: double.infinity,
          child: FilledButton.icon(
            onPressed: _isSaving ? null : _save,
            icon: const Icon(Icons.download_done_rounded),
            label: Text(
              _isSaving ? strings.actionSaving : strings.actionSave,
            ),
            style: FilledButton.styleFrom(
              padding: const EdgeInsets.symmetric(vertical: 14),
              shape: RoundedRectangleBorder(
                borderRadius: BorderRadius.circular(14),
              ),
            ),
          ),
        ),
      ],
    );
  }
}
